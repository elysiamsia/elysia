/**
 * data/bdays.js — 生日表：**全站唯一数据源**
 *
 * 呀，这一份短得几乎不像个文件，但它是**全站唯一**知道谁哪天生日的地方♥
 *
 * ── 为什么单独一个文件 ───────────────────────────────────────────────
 *   在它之前，「今天是不是她的生日」这件事散落在各页自己的脚本里
 *   （`var BM = 3, BD = 30;` 这种）。13 页 = 13 处，改一处漏十二处。
 *   这和 HANDOVER §10.5 里合并 `BUILT` 开关是**同一条教训**：
 *   **同一件事两处维护，迟早漏一处。**
 *
 * ── 格式 ─────────────────────────────────────────────────────────────
 *   键 = **页面的文件路径**（相对站点根），值 = `[月, 日]`
 *
 *   ⚠ **月份从 0 起**（0 = 一月），与页面里既有的 `var BM = 3, BD = 30`
 *     写法一致 —— 也就是直接用 `new Date(y, m, d)` 的语义。
 *     写的时候心里过一遍：4 月 30 日 → `[3, 30]`。
 *
 *   键写成文件路径而不是 URL 路径，是因为 `ElysiaBottom.pageKey()`
 *   会把 `/sakura/` 和 `/sakura/index.html` 都归一成 `sakura/index.html` ——
 *   线上是前者，本地双击打开是后者，两种都得认。
 *
 * ── 规矩 ─────────────────────────────────────────────────────────────
 *   · **只有「有确定生日」的英桀才写在这里。** 查不到 / 标注【待考】的，
 *     整条不写 —— 页面自然就不显示倒计时槽，不会显示成错的。
 *   · **可以先把还没建的页也写上**（下面的 hua / griseo 就是）。
 *     页建好之后自动生效，不用回头改这里。
 *   · ⚠ 其余 8 位英桀的生日**本轮未查**。按项目纪律：**不猜**。
 *
 * ⚠ 这是**纯数据模块**：不含 DOM 操作、不含格式化逻辑。
 *   怎么渲染是 `assets/bottom.js` 的事。
 */
